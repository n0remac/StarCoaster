#!/usr/bin/env python3
"""Generate the native paint descriptors from registered visual profiles and G2 paths."""

import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
DIRECTIONS = ("east", "southeast", "south", "southwest", "west", "northwest", "north", "northeast")
STATES = ("idle", "walk", "attack", "heal", "death")
LEGACY_G2_COUNT = 601


def write_if_changed(path: Path, contents: str) -> None:
    if not path.is_file() or path.read_text() != contents:
        path.write_text(contents)


def frame_names(state: str, animation: dict) -> list[list[str]]:
    if "banks" in animation:
        return [[f"{state if animation.get('name_without_zero') else state + str(pose)}_{direction}.png"
                 for direction in DIRECTIONS] for pose in range(len(animation["banks"]))]
    return [[f"{state}{pose}.png"] * 8 for pose in range(len(animation["frames"]))]


def animations(profile: dict, prefix: str, images: dict[str, int], body: bool) -> list[str]:
    source = profile["animations"]
    lines = []
    for state in STATES:
        if state not in source:
            continue
        animation = source[state]
        if "fallback" in animation:
            target = animation["fallback"]
            if target not in source or "fallback" in source[target]:
                raise ValueError(f"Invalid {state} fallback: {target}")
            animation = source[target]
        names = frame_names(state if "fallback" not in source[state] else source[state]["fallback"], animation)
        if len(names) > 10 or not names:
            raise ValueError(f"Unsupported frame count for {state}")
        rows = []
        for row in names:
            keys = [f"bridge/{prefix}{name}" for name in row]
            missing = [key for key in keys if key not in images]
            if missing:
                raise ValueError(f"Missing G2 sprite {missing[0]}")
            rows.append("{" + ", ".join(f"SPR_G2_BEGIN + {images[key]}" for key in keys) + "}")
        rows += ["{0}"] * (10 - len(rows))
        ticks = animation["ticks"]
        lines.append(f'    {{ "{state}", {len(names)}, {ticks}, {{' + ", ".join(rows) + "} },")
    if "idle" not in source or (body and "death" not in source):
        raise ValueError("Conventional actor visuals require idle and death states")
    return lines


def generate(upstream: Path) -> None:
    catalog = json.loads((ROOT / "bridge-protocol/starcraft-types.json").read_text())
    visuals = json.loads((ROOT / "bridge-protocol/starcraft-visuals.json").read_text())
    sprite_entries = json.loads((upstream / "resources/g2/sprites.json").read_text())
    images = {entry["path"]: index for index, entry in enumerate(sprite_entries)}
    if len(images) != len(sprite_entries):
        raise ValueError("Duplicate G2 sprite path")
    if len(sprite_entries) < LEGACY_G2_COUNT or sprite_entries[LEGACY_G2_COUNT - 1]["path"] != "bridge/flame/burst6_northeast.png":
        raise ValueError("Legacy G2 sprite IDs have changed")
    extra_count = len(sprite_entries) - LEGACY_G2_COUNT
    include = upstream / "src/openrct2/BridgeVisualSpriteIds.inc"
    write_if_changed(include, "// Generated by scripts/generate-starcraft-visual-registry.py.\n" +
                     "".join(f"    SPR_BRIDGE_GENERATED_{index},\n" for index in range(extra_count)))

    output = ["// Generated by scripts/generate-starcraft-visual-registry.py.",
              "#pragma once", "#include <cstdint>", "#include <cstddef>",
              "struct BridgeVisualAnimation { const char* motion; uint8_t count; uint8_t ticks; uint32_t images[10][8]; };",
              "struct BridgeVisualLayer { const BridgeVisualAnimation* animations; size_t count; bool targetFacing; };",
              "struct BridgeVisualType { const char* id; uint32_t healthBase; int16_t bounds[3]; bool flame; const BridgeVisualLayer* layers; size_t layerCount; };"]
    descriptors = []
    for unit in catalog["units"]:
        kind = unit["id"]
        profile = visuals["units"][unit["visual"]]
        asset = profile["asset"]
        layers = [("body", profile, "" if asset == "zergling" else asset + "/")]
        layers += [(attachment["name"], attachment, asset + "/" + attachment["name"] + "_")
                   for attachment in profile.get("attachments", [])]
        for name, layer, prefix in layers:
            rows = animations(layer, prefix, images, name == "body")
            output.append(f"static constexpr BridgeVisualAnimation kBridge_{asset}_{name}[] = {{")
            output.extend(rows)
            output.append("};")
        output.append(f"static constexpr BridgeVisualLayer kBridge_{asset}_layers[] = {{")
        output.extend(f"    {{ kBridge_{asset}_{name}, sizeof(kBridge_{asset}_{name}) / sizeof(BridgeVisualAnimation), "
                      f"{str(layer.get('facing') == 'native_target').lower()} }},"
                      for name, layer, _ in layers)
        output.append("};")
        health = "zergling" if asset == "zergling" else asset
        health_key = f"bridge/health/{health}0.png"
        if health_key not in images:
            raise ValueError(f"Missing health bar for {kind}")
        bounds = profile["bounds"]
        descriptors.append(f'    {{ "{kind}", SPR_G2_BEGIN + {images[health_key]}, '
                           f'{{ {bounds[0]}, {bounds[1]}, {bounds[2]} }}, '
                           f'{str(profile.get("effect") == "firebat_flame").lower()}, '
                           f'kBridge_{asset}_layers, {len(layers)} }},')
    output.append("static constexpr BridgeVisualType kBridgeVisualTypes[] = {")
    output.extend(descriptors)
    output.append("};")
    target = upstream / "src/openrct2/paint/BridgeVisualRegistry.h"
    write_if_changed(target, "\n".join(output) + "\n")
    print(f"Generated {len(descriptors)} actor descriptors and {extra_count} additional G2 IDs")


if __name__ == "__main__":
    generate(Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "upstream/openrct2")
